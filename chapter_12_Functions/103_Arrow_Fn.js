// Arrow Function (ES6)
const greet = function (name) {
    return name;
}

console.log(greet("Pramod"));

console.log("---------------");

const greet2 = (name) => name;
console.log(greet2("Bob"));

console.log("---------------");

const doubleIt = n => n * 2;
console.log(doubleIt(10));

console.log("---------------");

const printIt = name => console.log(name);
printIt("Dutta");

