// --- Common Naming Conventions in JavaScript ---

// 1. camelCase — for variables & functions (JavaScript standard)
var firstName = "Girish";
var lastName = "Nandanwar";

// 2. PascalCase — for classes & constructors
let UserProfile = "PascalCase";
let ShoppingCart = "class name style";

// 3. snake_case — rarely in JS, common in Python / DB columns
var first_name = "Girish";
var last_name = "Nandanwar";

// 4. UPPER_SNAKE_CASE (SCREAMING_SNAKE_CASE) — for constants
const MAX_RETRY_COUNT = 3;
const API_BASE_URL = "https://example.com";

// 5. kebab-case — NOT valid in JavaScript (hyphen is minus operator)
// var user-name = "Girish";  // ❌ SyntaxError

// 6. Hungarian Notation — prefix indicates type (older style)
var strName = "Girish";        // string
var numAge = 30;               // number
var isActive = true;           // boolean prefix
var arrItems = [1, 2, 3];      // array
var fnCallback = function () { }; // functio
