console.log(typeof "2000"); // string

let str = "Hello, World!";
console.log(str.length); // Output: 13 [Length always starts from 1]

// Access by index
console.log(str[0]); // Output: H
console.log(str[7]); // Output: W
console.log(str.charAt(1)); // Output: e
console.log(str.at(-1)); // Output: !
console.log(str.at(-6)); // Output: W

// index start from 0
// length starts from 1

console.log(str.charAt(0)); // Output: H
console.log(str.charCodeAt(0)); // Output: 72 (ASCII code for 'H')


